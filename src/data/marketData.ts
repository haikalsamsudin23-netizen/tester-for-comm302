// Helper to generate realistic 20-point candle series for stock chart drawer
function generateCandles(basePrice: number, trend: number): StockItem['candles'] {
  const candles: StockItem['candles'] = [];
  let curr = basePrice * (1 - trend * 0.015);
  const times = [
    '09:30', '09:45', '10:00', '10:30', '11:00', '11:30',
    '12:00', '12:30', '13:00', '13:30', '14:00', '14:30',
    '15:00', '15:15', '15:30', '15:45', '16:00'
  ];

  times.forEach((t) => {
    const change = (Math.random() - 0.47) * (basePrice * 0.008);
    const open = curr;
    const close = +(curr + change).toFixed(2);
    const high = +(Math.max(open, close) + Math.random() * (basePrice * 0.004)).toFixed(2);
    const low = +(Math.min(open, close) - Math.random() * (basePrice * 0.004)).toFixed(2);
    const volume = Math.floor(800000 + Math.random() * 2500000);
    curr = close;
    candles.push({ time: t, open, high, low, close, volume });
  });

  return candles;
}

